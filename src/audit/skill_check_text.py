"""Check a draft against the glossary. Python 3 standard library only.

Usage:
    python scripts/check_text.py draft.txt
    python scripts/check_text.py < draft.txt

It prints one line per problem, as `line:column: rule`, and exits 1 if there are any, so
a writer or a writing tool gets the same answer every time.

Each line of the draft is read as one string, the way the audit reads each row of its
table. A line that starts with # is a heading, where title case is allowed. Words in
backticks are code and aren't checked.

The rules follow `audit check` (src/audit/check.py in the audit repo):
- Words to avoid count in any case. Retired (deprecated) names count when capitalised,
  because a lowercase "space" is the general word, not the old product name.
- Terms to use are flagged when their capitals, spaces or hyphens differ from the
  glossary. All-lowercase uses are left alone: they may be the general word ("a
  project"), which only a person can tell. ALL CAPS is styling, so it's left alone too.
- Plurals and a leading company name count as the same term.
The audit's page-specific exceptions, such as changelog pages and rename guides, don't
apply to a new draft, so they aren't here.

This file is generated by `audit skill`, so the audit and the skill can't drift apart.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

# Filled in by `audit skill`. A term can start with the company name or not.
COMPANY = "{{display_name}}"
GLOSSARY = Path(__file__).resolve().parent.parent / "references" / "glossary.csv"

# A capital straight after one of these starts a sentence, so it isn't a wrong capital.
SENTENCE_BREAK = re.compile(r"[.!?:;\"'“(\[]\s*$")
# Markdown list markers and headings come before the string itself.
MARKER = re.compile(r"^\s*(?:#+|[-*>]|\d+[.)])\s+")
CODE = re.compile(r"`[^`]*`")


def strip_company(words: list[str]) -> list[str]:
    if len(words) > 1 and words[0].lower() == COMPANY.lower():
        return words[1:]
    return words


def shape(form: str) -> str:
    """The parts of a form that make it a variant: case, spaces and hyphens. A plural or
    the company name in front is normal grammar, so both go."""
    text = " ".join(strip_company(form.split()))
    if len(text) > 3 and text.endswith("s") and not text.endswith("ss"):
        text = text[:-1]
    return text


def pattern_for(term: str) -> re.Pattern[str]:
    """The term in any case, with spaces or hyphens, plural or not, with or without the
    company name in front. Word boundaries keep "kill" out of "skill"."""
    words = strip_company(term.replace("-", " ").split())
    if len(words[-1]) > 3:
        words[-1] = words[-1].removesuffix("s")
    body = r"[\s-]?".join(re.escape(w) for w in words)
    return re.compile(rf"\b(?:{re.escape(COMPANY)}\s+)?{body}(?:es|s)?\b", re.IGNORECASE)


def inside_identifier(text: str, start: int, end: int) -> bool:
    """A match inside a file name, URL or code ID ("sonar-pro") isn't prose."""
    before = text[start - 1] if start > 0 else ""
    after = text[end] if end < len(text) else ""
    after_next = text[end + 1] if end + 1 < len(text) else ""
    matched = text[start:end]
    return (
        (before != "" and before in "-_/.")
        or (after != "" and after in "-_/")
        or (after == "." and after_next.isalnum())
        or ("-" in matched and matched == matched.lower())
    )


def is_plural(form: str) -> bool:
    words = re.sub(r"['’]s$", "", form).split()
    last = words[-1] if words else ""
    return len(last) > 3 and last.endswith("s") and not last.endswith("ss")


def squash(text: str) -> str:
    return re.sub(r"[\s-]", "", text).lower()


def spelling_problem(term: str, form: str, text: str, start: int, heading: bool) -> str:
    """'' if a use of a term to use is fine here, or the kind of variant it is."""
    written = shape(form)
    if written == written.lower() and term != term.lower():
        return ""
    if len(written) > 1 and written == written.upper() and term != term.upper():
        return ""
    # "AI Assistant" names one thing. It isn't a variant of the plural term "AI assistants".
    if is_plural(term) and not is_plural(form):
        return ""
    base = shape(term)
    allowed = {base}
    if start == 0 or SENTENCE_BREAK.search(text[:start]):
        allowed.add(base[:1].upper() + base[1:])
    if heading:
        allowed.add(" ".join(w[:1].upper() + w[1:] for w in base.split()))
    # "Pro Searches" loses only its "s" in shape(), leaving "Pro Searche".
    if written.endswith("e") and written[:-1].lower() in {a.lower() for a in allowed}:
        written = written[:-1]
    if written in allowed:
        return ""
    if written.lower() in {a.lower() for a in allowed}:
        return "capitalisation"
    if squash(written) in {squash(a) for a in allowed}:
        return "spelling or spacing"
    return "other variant"


def problems(lines: list[str], entries: list[dict[str, str]]) -> list[tuple[int, int, str, str]]:
    """(line, column, term, rule) for every problem. Lines and columns count from 1."""
    patterns = {e["term"]: pattern_for(e["term"]) for e in entries}
    found = []
    for number, raw in enumerate(lines, start=1):
        marker = MARKER.match(raw)
        offset = marker.end() if marker else 0
        heading = raw.lstrip().startswith("#")
        # Blank out code so its offsets still line up with the line as written.
        text = CODE.sub(lambda m: " " * len(m.group()), raw[offset:])
        for entry in entries:
            term, status = entry["term"], entry["status"]
            # A longer glossary term that contains this one ("API Portal" holds "portal")
            # already reports those words, so they aren't reported twice.
            longer = [
                m.span()
                for other in entries
                if len(other["term"]) > len(term) and term.lower() in other["term"].lower()
                for m in patterns[other["term"]].finditer(text)
            ]
            for match in patterns[term].finditer(text):
                start, end = match.span()
                form = match.group()
                if inside_identifier(text, start, end):
                    continue
                if status in ("avoid", "deprecated"):
                    if any(s <= start and end <= e for s, e in longer):
                        continue
                    if status == "deprecated" and form == form.lower() and term != term.lower():
                        continue
                    kind = "deprecated name" if status == "deprecated" else "avoided term"
                    replacement = entry["use_instead"].strip()
                    fix = f"Use '{replacement}' instead." if replacement else (
                        f"Reword without '{term}'."
                    )
                else:
                    kind = spelling_problem(term, form, text, start, heading)
                    if not kind:
                        continue
                    fix = f"Write '{term}'."
                rule = f"{kind} '{form}'. {fix}"
                found.append((number, offset + start + 1, term, rule))
    return sorted(found)


def read_glossary(path: Path = GLOSSARY) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return [row for row in csv.DictReader(f) if row["term"].strip()]


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        print("Usage: python scripts/check_text.py [file]", file=sys.stderr)
        return 2
    text = Path(argv[0]).read_text(encoding="utf-8") if argv else sys.stdin.read()
    found = problems(text.splitlines(), read_glossary())
    for line, column, _term, rule in found:
        print(f"{line}:{column}: {rule}")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
